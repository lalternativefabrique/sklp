const (
	agentsMDBegin = "<!-- sklp:begin (generated by `sklp agents-md`; edits inside are overwritten) -->"
	agentsMDEnd   = "<!-- sklp:end -->"
	claudeImport  = "@AGENTS.md"
)

type agentsWatch struct {
	Name      string `yaml:"name"`
	Service   string `yaml:"service"`
	Space     string `yaml:"space"`
	ImageRepo string `yaml:"image_repo"`
}

func agentsMDCommand() cli.Command {
	return cli.Command{
		Name:  "agents-md",
		Short: "Write this repo's deploy facts into AGENTS.md so AI agents know how it ships",
		Long: "Generates a section of AGENTS.md from .sklp/deploy-root.yaml, .sklp/image-watches.yaml\n" +
			"and the pipelines: what core reconciles from main, which images roll on publish, and\n" +
			"when `sklp deploy apply` is (not) the way. Only the marked section is rewritten.\n" +
			"A CLAUDE.md without `@AGENTS.md` gets that import appended. --check fails when\n" +
			"the section is stale, for a git hook.",
		Flags: []cli.Flag{
			{Name: "repo", Type: cli.StringFlag, StringDefault: ".", Usage: "repository root"},
			{Name: "check", Type: cli.BoolFlag, Usage: "exit 1 when AGENTS.md is out of date, write nothing"},
		},
		Run: func(_ context.Context, args cli.Args) int {
			return runAgentsMD(args.String("repo"), args.Bool("check"))
		},
	}
}

func runAgentsMD(repo string, check bool) int {
	section, err := agentsMDSection(repo)
	if err != nil {
		fmt.Fprintln(os.Stderr, "sklp agents-md:", err)
		return 1
	}
	path := filepath.Join(repo, "AGENTS.md")
	current, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		fmt.Fprintln(os.Stderr, "sklp agents-md:", err)
		return 1
	}
	next := spliceSection(current, section)
	if check {
		if !bytes.Equal(current, next) {
			fmt.Fprintln(os.Stderr, "sklp agents-md: AGENTS.md is out of date, run `sklp agents-md`")
			return 1
		}
		return 0
	}
	if !bytes.Equal(current, next) {
		if err := os.WriteFile(path, next, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "sklp agents-md:", err)
			return 1
		}
		fmt.Println("updated AGENTS.md")
	}
	if err := ensureClaudeImport(filepath.Join(repo, "CLAUDE.md")); err != nil {
		fmt.Fprintln(os.Stderr, "sklp agents-md:", err)
		return 1
	}
	return 0
}

func spliceSection(current []byte, section string) []byte {
	block := agentsMDBegin + "\n" + section + agentsMDEnd + "\n"
	s := string(current)
	begin := strings.Index(s, agentsMDBegin)
	end := strings.Index(s, agentsMDEnd)
	if begin >= 0 && end > begin {
		rest := strings.TrimPrefix(s[end+len(agentsMDEnd):], "\n")
		return []byte(s[:begin] + block + rest)
	}
	if strings.TrimSpace(s) == "" {
		return []byte(block)
	}
	return []byte(strings.TrimRight(s, "\n") + "\n\n" + block)
}

func ensureClaudeImport(path string) error {
	b, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, line := range strings.Split(string(b), "\n") {
		if strings.TrimSpace(line) == claudeImport {
			return nil
		}
	}
	return os.WriteFile(path, []byte(strings.TrimRight(string(b), "\n")+"\n\n"+claudeImport+"\n"), 0o644)
}

func agentsMDSection(repo string) (string, error) {
	var b strings.Builder
	b.WriteString("## Shipping this repo with sklp\n\n")

	root, err := readDeployRoot(repo)
	if err != nil {
		return "", err
	}
	watches, err := readWatches(repo)
	if err != nil {
		return "", err
	}

	if root == nil {
		b.WriteString("No `.sklp/deploy-root.yaml`: nothing here is reconciled by core. A deploy is `sklp deploy apply <stack> -context <node>`; print the target first (`sklp deploy context list`).\n\n")
	} else {
		b.WriteString("These spaces are **reconciled by core from the default branch**. A merge to main reaches the node within seconds. **Never `sklp deploy apply` them**: it pushes your local file to whatever context is active and is undone by the next reconcile.\n\n")
		b.WriteString("| Space | Manifest | Node |\n|---|---|---|\n")
		for _, d := range root.Deployments {
			node := d.Node
			if node == "" {
				node = root.Node
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | `%s` |\n", d.Space, d.Path, node)
		}
		b.WriteString("\n")
	}

	if len(watches) > 0 {
		b.WriteString("**Image watches**: publishing a new tag of these images rolls the service by itself (no apply, no manifest edit):\n\n")
		b.WriteString("| Image | Service | Space |\n|---|---|---|\n")
		for _, w := range watches {
			fmt.Fprintf(&b, "| `%s` | `%s` | `%s` |\n", w.ImageRepo, w.Service, w.Space)
		}
		b.WriteString("\n")
	}

	if pipes, err := layout.New(repo).Pipelines(); err == nil && len(pipes) > 0 {
		b.WriteString("**Pipelines** (`sklp run <name>`): ")
		for i, p := range pipes {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "`%s`", p)
		}
		b.WriteString("\n\n")
	}

	b.WriteString("### How a change ships\n\n")
	b.WriteString("1. `sklp flow start <name>` → work → `sklp flow end` (opens the PR).\n")
	b.WriteString("2. Merge the PR. A manifest change (`.sklp/**/deploy.yaml`) is live once core reconciles main.\n")
	b.WriteString("3. Image change: from a clean main, `sklp run publish…`; the watch rolls it.\n\n")
	b.WriteString("### When a change does not land\n\n")
	b.WriteString("Core rejects a whole manifest that references a secret the project lacks (or one not deploy-readable), and then applies nothing from it. Check names with `sklp secret list -project <id>` (`sklp whoami -json` gives the id). `sklp deploy restart` only restarts what the node already holds; it never reads git.\n\n")
	b.WriteString("Read the live state with `-json`: `sklp whoami -json`, `sklp deploy ls -json`, `sklp deploy mesh ls -json`, `sklp deploy datastores -json`, `sklp deploy restores -json`.\n")
	return b.String(), nil
}

func readDeployRoot(repo string) (*domain.Root, error) {
	raw, err := os.ReadFile(filepath.Join(repo, ".sklp", "deploy-root.yaml"))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return domain.ParseRoot(raw)
}

func readWatches(repo string) ([]agentsWatch, error) {
	raw, err := os.ReadFile(filepath.Join(repo, ".sklp", "image-watches.yaml"))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var f struct {
		Watches []agentsWatch `yaml:"watches"`
	}
	if err := yaml.Unmarshal(raw, &f); err != nil {
		return nil, fmt.Errorf("parse image-watches.yaml: %w", err)
	}
	sort.SliceStable(f.Watches, func(i, j int) bool {
		return f.Watches[i].Space+f.Watches[i].Service < f.Watches[j].Space+f.Watches[j].Service
	})
	return f.Watches, nil
}
