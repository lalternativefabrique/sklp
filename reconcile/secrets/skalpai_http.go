package secrets

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"strings"
	"time"

	"github.com/lalternativefabrique/sklp/reconcile/deployconfig/domain"
)

// skalpai_http.go reads a project's secrets from Skalpai over HTTP.
//
// It is the node's counterpart to core's in-process SkalpaiProvider: the same
// contract, the same manifest declaration (`store: skalpai`), resolved by an
// HTTP call instead of a Go one. That symmetry is the point — a repo does not
// state where its reconciler runs, so the same secrets.yaml has to work on
// both sides.
//
// The credential is the token Skalpai issued for this node. It is deliberately
// NOT the node's own control token: that one is generated by the node so core
// can get in, and presenting it back would offer a secret the node minted
// itself.

// DefaultTimeout bounds a resolve. A reconcile pass that hangs on the API is
// worse than one that fails: the loop retries on the next tick, and a stuck
// pass never does.
const DefaultTimeout = 30 * time.Second

// SkalpaiHTTPProvider resolves `store: skalpai` references against the API.
type SkalpaiHTTPProvider struct {
	// BaseURL is Skalpai's API root, e.g. https://api.skalpai.dev.
	BaseURL string
	// Token is the node service token, read from the environment rather than
	// a file the repo could carry.
	Token string
	// ProjectID names the project whose secrets this node resolves. It is
	// configuration rather than a manifest field: a repo saying which project
	// to read from would let one repo name another's.
	ProjectID string

	Client *http.Client
}

type resolveRequest struct {
	ProjectID string `json:"project_id"`
	Reason    string `json:"reason,omitempty"`
}

type resolveResponse struct {
	Secrets map[string]string `json:"secrets"`
}

// Fetch implements Provider.
//
// The refs are not sent: the endpoint returns everything the project marked
// deploy-readable, and the caller keeps what its manifest declared. Sending
// them would tell the audit log which names a node was interested in without
// changing what it could read — more disclosure for no less access.
func (p *SkalpaiHTTPProvider) Fetch(ctx context.Context, _ domain.SecretStore, req domain.SecretRequest, _ []domain.SecretRef) (map[string]string, error) {
	if p.Token == "" {
		return nil, fmt.Errorf("no node token: set SKLP_NODE_TOKEN to resolve secrets from Skalpai")
	}
	projectID := p.ProjectID
	if projectID == "" {
		projectID = req.ProjectID
	}
	if projectID == "" {
		return nil, fmt.Errorf("no project to resolve secrets from")
	}

	body, err := json.Marshal(resolveRequest{ProjectID: projectID, Reason: req.Reason})
	if err != nil {
		return nil, fmt.Errorf("encode request: %w", err)
	}

	url := strings.TrimSuffix(p.BaseURL, "/") + "/api/internal/nodes/secrets/resolve"
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, url, bytes.NewReader(body))
	if err != nil {
		return nil, fmt.Errorf("build request: %w", err)
	}
	httpReq.Header.Set("Content-Type", "application/json")
	httpReq.Header.Set("Authorization", "Bearer "+p.Token)

	resp, err := p.client().Do(httpReq)
	if err != nil {
		// The URL can carry no credential, but the error text can quote the
		// request; the token lives in a header, so it is not in either.
		return nil, fmt.Errorf("reach Skalpai: %w", err)
	}
	defer resp.Body.Close()

	switch resp.StatusCode {
	case http.StatusOK:
	case http.StatusUnauthorized:
		return nil, fmt.Errorf("Skalpai rejected this node's token: reissue it and set SKLP_NODE_TOKEN")
	case http.StatusForbidden:
		return nil, fmt.Errorf("this node's token does not allow reading secrets")
	case http.StatusNotFound:
		// The endpoint answers 404 for a project outside this node's stack, so
		// the message says both things it can mean rather than guessing.
		return nil, fmt.Errorf("project %q not found, or not in this node's stack", projectID)
	default:
		return nil, fmt.Errorf("Skalpai returned %s", resp.Status)
	}

	var decoded resolveResponse
	if err := json.NewDecoder(resp.Body).Decode(&decoded); err != nil {
		return nil, fmt.Errorf("decode response: %w", err)
	}
	if decoded.Secrets == nil {
		decoded.Secrets = map[string]string{}
	}
	return decoded.Secrets, nil
}

func (p *SkalpaiHTTPProvider) client() *http.Client {
	if p.Client != nil {
		return p.Client
	}
	return &http.Client{Timeout: DefaultTimeout}
}

var _ Provider = (*SkalpaiHTTPProvider)(nil)
