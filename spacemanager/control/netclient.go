package control

// netclient.go is the NETWORK transport of the control client: it builds the
// SAME *Client type as Dial (so State/Logs/Apply/Exec/Down/Restart are reused
// verbatim) but pointed at an HTTPS endpoint with a Bearer token, instead of the
// local Unix socket. This is the kube-apiserver / Talos remote path: pilot a
// space from another machine WITHOUT ssh.
//
// It is NOT gated on embedded_runtime — a workstation built without the embedded
// runtime can still drive a remote supervisor (mirrors deploy_remote.go's ssh
// client). Only the SERVER side (netserve.go/tls.go/token.go) is gated.
//
// TLS trust model (self-signed cert generated by the server, no PKI):
//   - WithCAFingerprint pins the server cert's SHA-256 (TOFU): the only accepted
//     cert is the one whose fingerprint matches. This is the recommended remote mode.
//   - WithInsecure skips verification entirely (LAN bootstrap convenience). The
//     token still authenticates the SERVER's right to act, but the channel is not
//     authenticated — use only on a trusted network, then switch to a pin.

import (
	"context"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"encoding/hex"
	"errors"
	"fmt"
	"net"
	"net/http"
	"strings"
)

// DialOption tunes a DialNet client (TLS trust mode).
type DialOption func(*dialConfig)

type dialConfig struct {
	insecure    bool
	fingerprint string // normalized hex sha256 of the pinned server cert, or ""
}

// WithInsecure disables TLS verification (LAN bootstrap). Mutually exclusive with
// a pin: a pin always wins (it is strictly safer).
func WithInsecure() DialOption { return func(c *dialConfig) { c.insecure = true } }

// WithCAFingerprint pins the server certificate by its SHA-256 fingerprint (TOFU).
// Accepts the hex with or without ":" separators / "sha256:" prefix, any case.
func WithCAFingerprint(fp string) DialOption {
	return func(c *dialConfig) { c.fingerprint = normalizeFingerprint(fp) }
}

// DialNet builds a network control Client for server (e.g. "https://host:9443")
// authenticated by token. It does not connect yet — the first call surfaces the
// transport/auth error. server may omit the scheme (https:// is assumed).
func DialNet(server, token string, opts ...DialOption) (*Client, error) {
	if token == "" {
		return nil, errors.New("control: a token is required for the network transport (see `sklp deploy token`)")
	}
	var cfg dialConfig
	for _, o := range opts {
		o(&cfg)
	}

	baseURL, host, err := normalizeServer(server)
	if err != nil {
		return nil, err
	}

	tlsCfg, err := clientTLSConfig(cfg)
	if err != nil {
		return nil, err
	}
	// http.Transport derives the SNI from the URL; the raw exec dial must set
	// it too, or a front relaying by server name (ADR-019) answers with its
	// own certificate and the pin rejects it.
	if h, _, herr := net.SplitHostPort(host); herr == nil {
		tlsCfg.ServerName = h
	} else {
		tlsCfg.ServerName = host
	}

	auth := "Bearer " + token
	tr := &http.Transport{
		TLSClientConfig: tlsCfg,
		// No proxy / keepalive surprises: a direct dial to the supervisor.
		ForceAttemptHTTP2: false,
	}
	return &Client{
		space:   "", // remote: the space lives server-side; set by the caller for messages
		baseURL: baseURL,
		http: &http.Client{
			Transport: &bearerRoundTripper{token: auth, base: tr},
		},
		dialRaw: func(ctx context.Context) (net.Conn, error) {
			var d net.Dialer
			raw, derr := d.DialContext(ctx, "tcp", host)
			if derr != nil {
				return nil, derr
			}
			tlsConn := tls.Client(raw, tlsCfg)
			if herr := tlsConn.HandshakeContext(ctx); herr != nil {
				_ = raw.Close()
				return nil, herr
			}
			return tlsConn, nil
		},
		rawHost: host,
		rawAuth: "Authorization: " + auth + "\r\n",
	}, nil
}

// WithSpace targets the client at one named space on the remote node. Beyond
// labelling error messages, it now also sets routePrefix so every
// space-scoped request (Apply, State, Logs, ...) is sent to
// SpaceRoutePrefix(space) instead of the bare route — required for a
// multi-space node (ServeNetMulti) to know which of its supervisors a request
// is for. A single-space node (ServeNet) still answers its bare routes; call
// WithSpace only against a node you know is multi-space-aware, or rely on the
// bare (unprefixed) routes for a legacy single-space one.
func (c *Client) WithSpace(space string) *Client {
	c.space = space
	c.routePrefix = SpaceRoutePrefix(space)
	return c
}

// bearerRoundTripper injects Authorization: Bearer <token> on every request.
type bearerRoundTripper struct {
	token string // "Bearer <token>"
	base  http.RoundTripper
}

func (b *bearerRoundTripper) RoundTrip(req *http.Request) (*http.Response, error) {
	// Clone so we never mutate the caller's request (RoundTripper contract).
	r := req.Clone(req.Context())
	r.Header.Set("Authorization", b.token)
	return b.base.RoundTrip(r)
}

// clientTLSConfig builds the client TLS config for the chosen trust mode. A pin
// takes precedence over insecure; with neither, the system trust store is used
// (effectively unusable against a self-signed server cert, so the CLI requires
// one of the two).
func clientTLSConfig(cfg dialConfig) (*tls.Config, error) {
	tc := &tls.Config{MinVersion: tls.VersionTLS12}
	switch {
	case cfg.fingerprint != "":
		// Pin: skip the chain check and instead require the leaf cert's sha256 to
		// equal the pinned fingerprint (TOFU against a self-signed server cert).
		want := cfg.fingerprint
		tc.InsecureSkipVerify = true
		tc.VerifyPeerCertificate = func(rawCerts [][]byte, _ [][]*x509.Certificate) error {
			if len(rawCerts) == 0 {
				return errors.New("control: server presented no certificate")
			}
			got := sha256.Sum256(rawCerts[0])
			if hex.EncodeToString(got[:]) != want {
				return fmt.Errorf("control: server certificate fingerprint mismatch (pinned %s, got %x)", want, got)
			}
			return nil
		}
	case cfg.insecure:
		tc.InsecureSkipVerify = true
	}
	return tc, nil
}

// normalizeServer splits "https://host:port" (or "host:port") into the baseURL
// (scheme://host:port, no trailing slash) and the host:port for raw dialing.
func normalizeServer(server string) (baseURL, hostPort string, err error) {
	s := strings.TrimSpace(server)
	if s == "" {
		return "", "", errors.New("control: --server is required for the network transport")
	}
	if !strings.Contains(s, "://") {
		s = "https://" + s
	}
	s = strings.TrimSuffix(s, "/")
	if !strings.HasPrefix(s, "https://") {
		return "", "", fmt.Errorf("control: --server must be https:// (got %q)", server)
	}
	hostPort = strings.TrimPrefix(s, "https://")
	if hostPort == "" {
		return "", "", fmt.Errorf("control: --server has no host (%q)", server)
	}
	return s, hostPort, nil
}

// normalizeFingerprint lowercases a sha256 hex fingerprint and strips ":"
// separators and an optional "sha256:" prefix, so the user can paste any common
// rendering (server prints the bare lowercase hex).
func normalizeFingerprint(fp string) string {
	fp = strings.TrimSpace(fp)
	fp = strings.TrimPrefix(strings.ToLower(fp), "sha256:")
	fp = strings.ReplaceAll(fp, ":", "")
	return fp
}
