package devstack

import (
	"os"
	"path/filepath"
	"testing"
)

func TestNodeModulesVolumeOnlyForJSProjects(t *testing.T) {
	repo := t.TempDir()
	if got := nodeModulesVolumes(repo, "/workspace"); got != nil {
		t.Fatalf("a repo without package.json got %v", got)
	}
	if err := os.WriteFile(filepath.Join(repo, "package.json"), []byte("{}"), 0o644); err != nil {
		t.Fatal(err)
	}
	got := nodeModulesVolumes(repo, "/workspace")
	if len(got) != 1 || got[0] != "sklp-dev-node-modules:/workspace/node_modules" {
		t.Fatalf("got %v", got)
	}
}

func TestRunServiceSpecCarriesTheNodeModulesVolume(t *testing.T) {
	repo := t.TempDir()
	if err := os.WriteFile(filepath.Join(repo, "package.json"), []byte("{}"), 0o644); err != nil {
		t.Fatal(err)
	}
	ns := NamedService{Name: "web"}
	ns.Def.Run = "pnpm dev"
	spec := devServiceSpec(ns, repo, devToolchain{}, nil)
	if len(spec.Volumes) != 1 {
		t.Fatalf("run: service volumes = %v", spec.Volumes)
	}
	ns.Def.Run, ns.Def.Image = "", "postgres:17"
	if spec := devServiceSpec(ns, repo, devToolchain{}, nil); len(spec.Volumes) != 0 {
		t.Fatalf("image: service must keep only its declared volumes, got %v", spec.Volumes)
	}
}
